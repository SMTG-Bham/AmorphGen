"""Approximate Gaussian first-shell fitting bias for a structural ensemble.

The problem this closes
-----------------------
:mod:`amorphgen.analysis.exafs` reports a *geometric* N: neighbours
counted inside a cutoff. A published EXAFS N is a *fit parameter*,
obtained by fitting chi(k) with a harmonic model -- a Gaussian pair
distribution, three parameters (N, R, sigma^2), sometimes a floated E0.
For a crystalline shell the two agree. For a glass they need not, and
``skew`` in the descriptor table flags when they will not.

This module measures the difference instead of flagging it. It fits the
harmonic model to the ensemble's *own* EXAFS amplitude and reports the
N, R and sigma^2 of this approximate fit -- next to the
geometric values. The gap between them is the harmonic-fit bias, and it
is the quantity to hold up against a literature comparison that shows a
computed N sitting above a published one.

How the fit avoids needing FEFF
-------------------------------
The single-scattering EXAFS signal from a shell with pair distribution
P(R) is

    chi(k) = (S0^2 / k) Im[ f(k) e^{i phi(k)} G(k) ],
    G(k)   = \\int P(R) R^{-2} e^{-2R/lambda} e^{2ikR} dR

The backscattering amplitude f(k), the phase shift phi(k), S0^2 and the
1/k all multiply the model and the data *identically*, so they cancel
out of the *model*: everything structural lives in the complex
amplitude G(k), which is a direct sum over the ensemble's own distances:

    G(k) = (1/N_abs) \\sum_i R_i^{-2} e^{-2R_i/lambda} e^{2ikR_i}

No histogram, no binning, no scattering calculation. The harmonic model
is the same integral for a Gaussian P(R), with the R^{-2} e^{-2R/lambda}
envelope evaluated at the shell distance -- which is exactly the
approximation a harmonic fit makes:

    G_h(k) = N R^{-2} e^{-2R/lambda} e^{-2 sigma^2 k^2} e^{2ikR}

They do not cancel out of the *fit*. A real fit minimises the misfit in
k^w chi(k), so each k point of G is weighted by k^(w-1) |f(k)|. When the
model is right -- a Gaussian shell -- the weighting cannot move the
answer. When it is wrong, which is the case this module exists for, the
best-fit N depends on where in k the misfit is counted, and |f(k)| of a
light scatterer falls more than tenfold across a 3-12 A^-1 window.
Weighting by k^w alone over-counts high k, where an asymmetric shell
loses the most amplitude, and roughly doubled the bias: on a-Ga2O3 it
gave -22% where Larch, fitting FEFF chi(k) of the same 60 sites in the
usual way, gave -12.6%. Weighting by k^(w-1) |f(k)| gives -12.2%
(``docs/notes/exafs_crosscheck``).

So the residual carries |f(k)| of the scattering element, from a table
computed once with FEFF6L (:data:`BACKSCATTER_TABLE`, regenerated by
``docs/notes/exafs_crosscheck/generate_backscatter_table.py``). Only its
shape in k matters, and that is set by the scatterer: the table uses one
protocol for every element and matches the |f(k)| of a real a-Ga2O3
cluster to +/-10%, which moves N by 0.5%. The absorber-dependent
reduction factor is left out (1% in N), as is FEFF's k-dependent mean
free path in favour of the scalar lambda (another 1%).

Fitting G_h to G over a k window with that weighting is the analogue of
fitting chi(k), without the window artefacts of a Fourier filter.

How far to trust it
-------------------
"What a fit would report" is only as definite as the fit. Against Larch
on four shells (``docs/notes/exafs_crosscheck``): a-Ga2O3 Ga-O matched to
about a point of N. The broad a-TiO2 Ti-O and a-CaZrCl6 Zr-Cl shells
missed by 4-8 points -- but there Larch itself moved by several points
with the R window, and reproducing its exact procedure (real chi(k),
phase, windows) closed the gap for one shell and overshot for the other.
For the flat-topped Ca-Cl shell no harmonic procedure is stable. So the
precision is set by the shell, and :func:`fit_quality` says which case a
shell is in: from its shape and width, not the R-factor alone.

Cross-check with the descriptor table
-------------------------------------
For a Gaussian P(R) the fit must return the R that
:mod:`amorphgen.analysis.exafs` predicts from its first-order cumulant
correction, ``C1 - 2 sigma^2 (1/C1 + 1/lambda)``. It does, to four
decimal places, which is a mutual validation of two independently
derived pieces of machinery -- see ``test_harmonic.py``.

Note the small residual bias even for a perfectly symmetric shell,
around -0.5% in N. That is not an error: it is the difference between
carrying R^{-2} e^{-2R/lambda} inside the integral and evaluating it at
the shell distance, which is a real approximation of the harmonic model
and part of what it costs.

What this fit is not
--------------------
Two differences from a fit in Artemis or Larch, both deliberate:

- **No Fourier filter.** A real fit isolates the first shell with an
  R-window on the transform. Here the shell is already isolated by the
  pair cutoff, so no window is applied and none of its leakage appears.
  Minimising over the complex amplitude is the analogue of fitting the
  real and imaginary parts of the windowed transform, which is what a
  fitting package does.
- **No least-squares uncertainties on the fitted parameters.** The
  "data" here is an exact sum over the ensemble, not a noisy
  measurement, so a formal fit error bar would be meaningless. The
  uncertainty that does matter is ensemble sampling -- how much the
  answer would move with a different set of structures -- and
  :func:`fit_shells` estimates it by bootstrapping over whole
  structures (its ``bootstrap`` argument). The ``r_factor`` says how
  well the harmonic model describes the shell, which is a different
  question; see :func:`fit_quality`.

Floating E0
-----------
A real fit usually floats the edge energy. ``fit_e0=True`` does the
same, shifting the model's k grid by ``sqrt(k^2 - E0/3.81)``. It is
worth knowing what that buys: on an asymmetric shell it absorbs most of
the third-cumulant *phase* distortion -- the fit residual drops several
fold and R moves down -- while leaving the N bias essentially untouched,
because the amplitude loss comes from destructive interference across
the k range that no single energy shift can undo. A better-looking fit,
the same wrong N. The default is ``False`` so the reported bias is
attributable to the Gaussian assumption alone.
"""

from __future__ import annotations

import textwrap
from functools import lru_cache

import numpy as np

from .exafs import (DEFAULT_MFP, MIN_BOOTSTRAP_STRUCTURES, SKEW_THRESHOLD,
                    bootstrap_shell, collect_shell_distances,
                    shell_cumulants)

#: eV -> A^-2 for the photoelectron wavenumber, k^2 = (E - E0) / 3.8099821.
ETOK = 1.0 / 3.8099821

#: Default fit window (A^-1). 3-12 is the range most first-shell oxide
#: EXAFS fits are quoted over; the bias grows with kmax, so a comparison
#: against a published fit should use that paper's range.
DEFAULT_KMIN = 3.0
DEFAULT_KMAX = 12.0

#: Bootstrap resamples for the fitted parameters. Far below the tier-1
#: default because each resample is a full least-squares fit (tens of ms,
#: against ~0.1 ms for a cumulant).
#:
#: 50 is enough for what is claimed. The relative precision of a
#: bootstrap standard error is about 1/sqrt(2B), so B = 50 pins it to
#: ~10% -- immaterial next to the bar's own unreliability for the
#: handful of structures a typical ensemble has. Confidence *intervals*
#: would need far more, and are not offered.
DEFAULT_BOOTSTRAP = 50

#: How far a fit can be read. Set against Larch fits of FEFF chi(k) for
#: the same sites (docs/notes/exafs_crosscheck): tier 2 matched them to
#: ~1 point of N for a-Ga2O3 Ga-O, missed by 4-8 points for the broad
#: a-TiO2 Ti-O and a-CaZrCl6 Zr-Cl shells -- where a real fit itself moves
#: that much with the analyst's window and fitting-space choices -- and
#: by ~30 points for the flat-topped Ca-Cl shell, where it moves by tens.
#: The R-factor is of the |f(k)|-weighted residual, in which every shell
#: tested fitted at 0.001-0.017 and Ca-Cl at 0.02-0.05: on its own it no
#: longer separates a usable fit from an unusable one, so the shell's
#: shape and width are checked too.
R_FACTOR_POOR = 0.015
R_FACTOR_FAILED = 0.1

#: Debye-Waller attenuation exp(-2 sigma^2 kmax^2) below which a shell is
#: "broad": so little of its signal survives to kmax that N and sigma^2
#: trade off, and the N a real fit reports depends on fitting choices by
#: several percent. 1.5% at kmax = 12 A^-1 is sigma^2 ~ 0.015 A^2,
#: between a-Ga2O3 Ga-O (0.008-0.010, matched) and a-TiO2 Ti-O (0.021).
DW_ATTENUATION_POOR = 0.015

#: Size of the fourth-cumulant amplitude correction at kmax,
#: (2/3) |C4| kmax^4 (the cumulant expansion of Bunker 1983), above which a
#: *symmetric* shell is too non-Gaussian for a harmonic fit to mean
#: anything. a-CaZrCl6 Ca-Cl: ~2.9 -- tier 2 and Larch disagreed by 30
#: points, and Larch itself by tens of percent across fitting choices. A
#: narrow flat shell (uniform, sigma^2 0.003) is ~0.2 and fits cleanly,
#: which is why |kurt| alone is not the test. Skewed shells are left out:
#: their long-tail kurtosis comes with the very bias tier 2 measures, and
#: a-Ga2O3 Ga-O (~1.9 here) matched Larch to a point.
C4_TERM_FAILED = 1.0

#: What each quality flag means, for the report.
QUALITY_FLAG_TEXT = {
    "not-converged": "the least-squares fit did not converge",
    "r-factor": "the harmonic model misfits the shell's own amplitude",
    "non-gaussian": ("symmetric but non-Gaussian, and broad enough for it "
                     f"to matter ((2/3)|C4| kmax^4 > {C4_TERM_FAILED:g}): the "
                     "N a real fit reports depends on the analyst's "
                     "choices by tens of percent"),
    "broad": (f"broad shell (under {100 * DW_ATTENUATION_POOR:.1f}% of its "
              "signal left at kmax): N and sigma^2 trade off, and a real "
              "fit's N moves by several percent with the fitting choices"),
}


def fit_quality_flags(r_factor, converged=True, skew=None, kurt=None,
                      sigma2=None, kmax=None):
    """Why a fit is less than good, as ``(level, code)`` pairs.

    ``level`` is ``"poor"`` or ``"failed"``; ``code`` is a key of
    :data:`QUALITY_FLAG_TEXT`. Shape and width are checked only when all
    of ``skew``, ``kurt``, ``sigma2`` (the geometric C2) and ``kmax`` are
    given, so a bare R-factor still classifies.
    """
    flags = []
    if not converged:
        flags.append(("failed", "not-converged"))
    if not np.isfinite(r_factor) or r_factor > R_FACTOR_FAILED:
        flags.append(("failed", "r-factor"))
    elif r_factor > R_FACTOR_POOR:
        flags.append(("poor", "r-factor"))
    if None in (skew, kurt, sigma2, kmax):
        return flags
    c4_term = (2.0 / 3.0) * abs(kurt) * (sigma2 * kmax ** 2) ** 2
    if abs(skew) <= SKEW_THRESHOLD and c4_term > C4_TERM_FAILED:
        flags.append(("failed", "non-gaussian"))
    if np.exp(-2.0 * sigma2 * kmax ** 2) < DW_ATTENUATION_POOR:
        flags.append(("poor", "broad"))
    return flags


def fit_quality(r_factor, converged=True, **shape):
    """``"good"``, ``"poor"`` or ``"failed"``: how far a fit can be read.

    A failed fit has no meaningful N, R or sigma^2, so no bias either. A
    poor one shows the direction and rough size of the bias, not a number
    to hold against a published N. ``shape`` takes the ``skew``,
    ``kurt``, ``sigma2`` and ``kmax`` of :func:`fit_quality_flags`.
    """
    levels = {level for level, _ in
              fit_quality_flags(r_factor, converged, **shape)}
    return ("failed" if "failed" in levels else
            "poor" if "poor" in levels else "good")


#: Per-element backscattering amplitude |f(k)|, relative to this module.
#: Generated with FEFF6L ("Based on or developed using Distribution:
#: FEFF6L, Copyright (c) [2002] University of Washington").
BACKSCATTER_TABLE = "data/backscatter_feff6l.json"


@lru_cache(maxsize=1)
def _backscatter_table():
    import json
    import os
    with open(os.path.join(os.path.dirname(__file__), BACKSCATTER_TABLE)) as fh:
        table = json.load(fh)
    return (np.asarray(table["k"], dtype=float),
            {el: np.asarray(a, dtype=float)
             for el, a in table["amplitude"].items()})


def backscattering_amplitude(element, k):
    """|f(k)| of ``element`` as a scatterer, or None if not tabulated.

    Only the shape in k is meaningful for the fit weighting; see the
    module docstring.
    """
    grid, amplitudes = _backscatter_table()
    if element not in amplitudes:
        return None
    return np.interp(np.asarray(k, dtype=float), grid, amplitudes[element])


def _residual_weight(k, kweight, scatterer):
    """Per-k weight of the residual, and whether |f(k)| went into it.

    With a scatterer, the weight a real k^w chi(k) fit puts on G(k):
    k^(w-1) |f(k)|. Without one, bare k^w -- the residual before the
    a-Ga2O3 cross-check, kept for comparison; it overstates the bias.
    """
    if scatterer is None:
        return k ** kweight, False
    amplitude = backscattering_amplitude(scatterer, k)
    if amplitude is None:
        import warnings
        warnings.warn(
            f"no backscattering amplitude tabulated for {scatterer!r}; "
            f"weighting the harmonic-fit residual by k^{kweight - 1} only, "
            f"so the reported N bias may be overstated", stacklevel=3)
        return k ** (kweight - 1), False
    return k ** (kweight - 1) * amplitude, True


#: Distances processed at once inside :func:`effective_amplitude`. The
#: sum is over an (nk x n_distances) array, so a long trajectory would
#: otherwise allocate gigabytes; chunking bounds it at a few tens of MB
#: without changing the result.
_CHUNK = 20000


def effective_amplitude(k, distances, n_absorbers, mfp=DEFAULT_MFP):
    """Complex EXAFS amplitude G(k) summed over the ensemble's distances.

    ``G(k) = (1/N_abs) sum_i R_i^-2 exp(-2 R_i / lambda) exp(2 i k R_i)``
    -- the exact sum, with no binning of P(R).

    Parameters
    ----------
    k : array_like
        Wavenumbers in A^-1.
    distances : array_like
        Every absorber-scatterer distance in the shell (A).
    n_absorbers : float
        Number of absorbing atoms the distances were collected from, so
        that ``|G|`` scales as the coordination number rather than as
        the ensemble size.
    mfp : float
        Photoelectron mean free path lambda (A).

    Returns
    -------
    ndarray
        Complex G(k), same length as ``k``.
    """
    k = np.asarray(k, dtype=float)
    r = np.asarray(distances, dtype=float)
    total = np.zeros(k.shape, dtype=complex)
    if r.size == 0:
        return total

    for start in range(0, r.size, _CHUNK):
        block = r[start:start + _CHUNK]
        envelope = block ** -2 * np.exp(-2.0 * block / mfp)
        total += (envelope[None, :]
                  * np.exp(2j * np.outer(k, block))).sum(axis=1)
    return total / float(n_absorbers)


def harmonic_amplitude(k, n, r, sigma2, mfp=DEFAULT_MFP, e0_shift=0.0):
    """The same amplitude for a Gaussian shell: the harmonic model.

    ``e0_shift`` (eV) moves the model onto a shifted wavenumber grid,
    ``k' = sqrt(k^2 - E0 / 3.81)``, the way a floated edge energy does
    in a real fit.
    """
    k = np.asarray(k, dtype=float)
    kp = np.sqrt(np.clip(k ** 2 - e0_shift * ETOK, 0.0, None))
    return (n * r ** -2 * np.exp(-2.0 * r / mfp)
            * np.exp(-2.0 * sigma2 * kp ** 2) * np.exp(2j * kp * r))


def fit_harmonic(distances, n_absorbers, mfp=DEFAULT_MFP, kmin=DEFAULT_KMIN,
                 kmax=DEFAULT_KMAX, kweight=2, nk=200, fit_e0=False,
                 scatterer=None):
    """Fit the harmonic (Gaussian) model to one shell's own amplitude.

    Parameters
    ----------
    distances : array_like
        Absorber-scatterer distances in the shell (A).
    n_absorbers : float
        Number of absorbing atoms behind those distances.
    mfp : float
        Photoelectron mean free path (A).
    kmin, kmax : float
        Fit window in A^-1. The bias grows with ``kmax``, so match the
        range of the paper being compared against.
    kweight : int
        k-weighting of the residual, as in a real fit (2 is usual).
    nk : int
        Number of k points sampled across the window.
    fit_e0 : bool
        Float an edge-energy shift as a fourth parameter. See the module
        docstring for what this does and does not fix.
    scatterer : str, optional
        Element of the scattering atoms, e.g. ``"O"``. Weights the
        residual by k^(kweight-1) |f(k)| as a real chi(k) fit does --
        pass it for a result comparable to a published fit.
        :func:`fit_shells` always does. Without it the residual is
        weighted by k^kweight alone, which overstates the bias.

    Returns
    -------
    dict
        ``N``, ``R``, ``sigma2`` and ``e0_shift`` as a harmonic fit would
        report them, plus ``r_factor`` (the usual EXAFS misfit,
        ``sum|data-model|^2 / sum|data|^2``, in the weighted residual),
        ``converged``, ``amplitude_weighted`` (whether |f(k)| went into
        the residual) and the fit settings (``kmin``, ``kmax``,
        ``kweight``, ``mfp``, ``fit_e0``, ``scatterer``).

    Raises
    ------
    ValueError
        If the shell is empty.
    """
    # Imported here, not at module level: docs/conf.py mocks numpy for
    # autodoc, and `import scipy` against a mocked numpy raises. The rest
    # of the package (voronoi, classical) defers scipy for the same reason.
    from scipy.optimize import least_squares

    r = np.asarray(distances, dtype=float)
    if r.size == 0:
        raise ValueError("cannot fit an empty shell")

    k = np.linspace(kmin, kmax, nk)
    weight, amplitude_weighted = _residual_weight(k, kweight, scatterer)
    data = effective_amplitude(k, r, n_absorbers, mfp)

    c1 = float(r.mean())
    c2 = float(((r - c1) ** 2).mean())

    start = [r.size / float(n_absorbers), c1, max(c2, 1e-6)]
    lower = [1e-9, 0.5 * c1, 0.0]
    upper = [np.inf, 2.0 * c1, 1.0]
    if fit_e0:
        start.append(0.0)
        lower.append(-25.0)
        upper.append(25.0)

    def residual(params):
        n, rr, s2 = params[0], params[1], params[2]
        e0 = params[3] if fit_e0 else 0.0
        diff = weight * (data - harmonic_amplitude(k, n, rr, s2, mfp, e0))
        return np.concatenate([diff.real, diff.imag])

    out = least_squares(residual, start, bounds=(lower, upper),
                        xtol=1e-14, ftol=1e-14)

    final = residual(out.x)
    denominator = float((np.abs(weight * data) ** 2).sum())
    r_factor = (float((final ** 2).sum()) / denominator
                if denominator > 0 else float("nan"))

    return {
        "N": float(out.x[0]),
        "R": float(out.x[1]),
        "sigma2": float(out.x[2]),
        "e0_shift": float(out.x[3]) if fit_e0 else 0.0,
        "r_factor": r_factor,
        "converged": bool(out.success),
        "kmin": float(kmin),
        "kmax": float(kmax),
        "kweight": int(kweight),
        "mfp": float(mfp),
        "fit_e0": bool(fit_e0),
        "scatterer": scatterer,
        "amplitude_weighted": amplitude_weighted,
        "n_paths": int(r.size),
        "n_absorbers": float(n_absorbers),
    }


def fit_shells(atoms_list, max_cutoff, get_cutoff_fn, pair=None,
               mfp=DEFAULT_MFP, kmin=DEFAULT_KMIN, kmax=DEFAULT_KMAX,
               kweight=2, nk=200, fit_e0=False,
               bootstrap=DEFAULT_BOOTSTRAP, seed=0, backscatter=True) -> dict:
    """Geometric descriptors and harmonic-fit values, side by side.

    Parameters
    ----------
    atoms_list, max_cutoff, get_cutoff_fn, pair
        As for :func:`amorphgen.analysis.exafs.compute_exafs_descriptors`.
        ``pair`` is ordered: ``"Ga-O"`` is the Ga edge with O scatterers.
    mfp, kmin, kmax, kweight, nk, fit_e0
        Passed to :func:`fit_harmonic`.
    backscatter : bool
        Weight each residual by the scattering element's |f(k)|, as a
        real chi(k) fit does (default). ``False`` reproduces the bare
        k^w weighting, which overstates the bias; it is there for
        comparison, not for results.
    bootstrap : int
        Resamples for the ensemble-sampling error bars on both columns,
        by resampling whole structures with replacement
        (:data:`DEFAULT_BOOTSTRAP`). 0 disables them. Each resample is a
        full fit, so this dominates the cost.
    seed : int
        Seed for the resampling, so the error bars are reproducible.

    Returns
    -------
    dict
        Keyed by ordered pair. Each value carries the geometric values
        (``N_geom``, ``R_geom``, ``sigma2_geom``, ``C3``, ``skew``), the
        fitted ones (``N_fit``, ``R_fit``, ``sigma2_fit``, ``e0_shift``),
        the differences (``N_bias``, ``N_bias_percent``, ``R_bias``,
        ``sigma2_bias_percent``) and the fit diagnostics (``r_factor``,
        ``converged``, ``fit_quality`` -- see :func:`fit_quality` --
        and the window settings).

    Notes
    -----
    ``*_err`` entries are ensemble-sampling standard errors. Read
    ``N_bias_percent`` against ``N_bias_percent_err`` before concluding
    that two ensembles differ: for a handful of structures the spread
    usually swamps the difference.

    A negative ``N_bias`` means a harmonic fit of this shell would report
    *fewer* neighbours than the ensemble contains -- the classic
    under-counting of an asymmetric glass shell, and the usual reason a
    published EXAFS N sits below a simulated coordination number.
    """
    shells = collect_shell_distances(atoms_list, max_cutoff, get_cutoff_fn,
                                     pair=pair)

    result = {}
    for key, shell in shells.items():
        r = shell["distances"]
        if r.size == 0:
            continue
        n_absorbers = shell["counts"].size
        n_geom = float(shell["counts"].mean())

        c1 = float(r.mean())
        delta = r - c1
        c2 = float((delta ** 2).mean())
        c3 = float((delta ** 3).mean())
        c4 = float((delta ** 4).mean()) - 3.0 * c2 ** 2
        sigma = np.sqrt(c2)
        skew = float(c3 / sigma ** 3) if sigma > 1e-12 else 0.0
        kurt = float(c4 / c2 ** 2) if sigma > 1e-12 else 0.0

        scatterer = shell["scatterer"] if backscatter else None
        fit = fit_harmonic(r, n_absorbers, mfp=mfp, kmin=kmin, kmax=kmax,
                           kweight=kweight, nk=nk, fit_e0=fit_e0,
                           scatterer=scatterer)

        # One statistic covering both columns, so the geometric and the
        # fitted error bars come from the same resamples and the bias
        # error is their paired spread rather than a quadrature guess.
        def _statistic(dd, cc):
            cum = shell_cumulants(dd, cc)
            f = fit_harmonic(dd, cc.size, mfp=mfp, kmin=kmin, kmax=kmax,
                             kweight=kweight, nk=nk, fit_e0=fit_e0,
                             scatterer=scatterer)
            return {"N_geom": cum["N"], "R_geom": cum["R"],
                    "sigma2_geom": cum["sigma2"], "skew": cum["skew"],
                    "N_fit": f["N"], "R_fit": f["R"],
                    "sigma2_fit": f["sigma2"],
                    "N_bias_percent": (100.0 * (f["N"] - cum["N"]) / cum["N"]
                                       if cum["N"] else float("nan"))}

        errs = bootstrap_shell(shell, _statistic, n_boot=bootstrap, seed=seed)
        shape = {"skew": skew, "kurt": kurt, "sigma2": c2, "kmax": kmax}

        result[key] = {
            "absorber": shell["absorber"],
            "scatterer": shell["scatterer"],
            "N_geom": n_geom,
            "R_geom": c1,
            "sigma2_geom": c2,
            "C3": c3,
            "skew": skew,
            "N_fit": fit["N"],
            "R_fit": fit["R"],
            "sigma2_fit": fit["sigma2"],
            "e0_shift": fit["e0_shift"],
            "N_bias": fit["N"] - n_geom,
            "N_bias_percent": (100.0 * (fit["N"] - n_geom) / n_geom
                               if n_geom else float("nan")),
            "R_bias": fit["R"] - c1,
            "sigma2_bias_percent": (100.0 * (fit["sigma2"] - c2) / c2
                                    if c2 > 0 else float("nan")),
            "r_factor": fit["r_factor"],
            "converged": fit["converged"],
            "kurt": kurt,
            "fit_quality": fit_quality(fit["r_factor"], fit["converged"],
                                       **shape),
            "quality_flags": ";".join(code for _, code in
                                      fit_quality_flags(fit["r_factor"],
                                                        fit["converged"],
                                                        **shape)),
            "amplitude_weighted": fit["amplitude_weighted"],
            "kmin": fit["kmin"],
            "kmax": fit["kmax"],
            "kweight": fit["kweight"],
            "mfp": fit["mfp"],
            "fit_e0": fit["fit_e0"],
            "n_structures": shell["n_structures"],
            **errs,
        }
    return result


def format_harmonic_report(result, bonded_only=True):
    """Human-readable table for :func:`fit_shells` output."""
    rows = _select_rows(result, bonded_only)
    if not rows:
        return "\n  No harmonic fits (no pairs inside the first-shell cutoff)."

    first = rows[0][1]
    bar = "=" * 78
    lines = ["", bar,
             "  Harmonic-fit bias  (approximate first-shell model)",
             bar,
             f"  Fit window k = {first['kmin']:.1f}-{first['kmax']:.1f} A^-1, "
             f"k-weight {first['kweight']}, "
             f"E0 {'floated' if first['fit_e0'] else 'fixed'}",
             "  Residual weighted by k^(w-1) |f(k)| of the scatterer, as in "
             "a chi(k) fit",
             ""]
    bare = [k for k, d in rows if not d.get("amplitude_weighted", False)]
    if bare:
        # Insert before the blank line that closes the header.
        lines[-1:-1] = [
            f"  NOT weighted by |f(k)|: {', '.join(bare)} -- their bias is "
            f"likely overstated",
            "  (no tabulated amplitude for the scatterer, or backscatter="
            "False)."]

    def cell(d, key, fmt, width):
        """'value +/- err' when the bootstrap ran, otherwise just the value."""
        v = format(d[key], fmt)
        err = d.get(f"{key}_err")
        text = v if err is None else f"{v} +/- {format(err, fmt)}"
        return f"{text:>{width}}"

    def shape_of(d):
        return {"skew": d.get("skew"), "kurt": d.get("kurt"),
                "sigma2": d.get("sigma2_geom"), "kmax": d.get("kmax")}

    def quality(d):
        if "fit_quality" in d:
            return d["fit_quality"]
        return fit_quality(d["r_factor"], d["converged"], **shape_of(d))

    def codes(d):
        if "quality_flags" in d:
            return [c for c in d["quality_flags"].split(";") if c]
        return [c for _, c in fit_quality_flags(d["r_factor"], d["converged"],
                                                **shape_of(d))]

    for key, d in rows:
        why = f": {', '.join(codes(d))}" if codes(d) else ""
        flag = ("" if quality(d) == "good" else
                f", FIT FAILED{why}" if quality(d) == "failed" else
                f", POOR FIT{why}")
        lines.append(f"  {key}   (skew {d['skew']:+.2f}, "
                     f"R-factor {d['r_factor']:.1e}{flag})")
        lines.append(f"    {'quantity':<14}{'geometric':>19}"
                     f"{'harmonic fit':>21}{'bias':>19}")
        lines.append("    " + "-" * 73)
        lines.append(f"    {'N':<14}{cell(d, 'N_geom', '.3f', 19)}"
                     f"{cell(d, 'N_fit', '.3f', 21)}"
                     f"{cell(d, 'N_bias_percent', '.1f', 17)} %")
        lines.append(f"    {'R (A)':<14}{cell(d, 'R_geom', '.3f', 19)}"
                     f"{cell(d, 'R_fit', '.3f', 21)}"
                     f"{d['R_bias']:>19.3f}")
        lines.append(f"    {'sigma2 (A^2)':<14}"
                     f"{cell(d, 'sigma2_geom', '.5f', 19)}"
                     f"{cell(d, 'sigma2_fit', '.5f', 21)}"
                     f"{d['sigma2_bias_percent']:>17.1f} %")
        if d["fit_e0"]:
            lines.append(f"    {'dE0 (eV)':<14}{'-':>19}"
                         f"{d['e0_shift']:>21.2f}{'-':>19}")
        lines.append("")

    failed = [k for k, d in rows if quality(d) == "failed"]
    if failed:
        lines.append(f"  FIT FAILED for {', '.join(failed)}: their 'harmonic "
                     "fit' column is not a")
        lines.append("  result, and their bias says nothing about the "
                     "structure.")
    present = []
    for _, d in rows:
        present += [c for c in codes(d) if c not in present]
    for code in present:
        pairs = ", ".join(k for k, d in rows if code in codes(d))
        for i, text in enumerate(textwrap.wrap(
                f"{code} ({pairs}): {QUALITY_FLAG_TEXT[code]}.", 74)):
            lines.append(("  " if i == 0 else "    ") + text)
    if failed or present:
        lines.append("")

    # The pair a reader should look at is the one furthest from its
    # geometric N, in either direction -- not merely the most negative --
    # among fits that mean something. Ranking failed fits in would pick
    # them *because* they are broken: a runaway N is the largest bias.
    usable = [kv for kv in rows if quality(kv[1]) != "failed"
              and np.isfinite(kv[1]["N_bias_percent"])]
    good = [kv for kv in usable if quality(kv[1]) == "good"]
    pool = good or usable
    if pool:
        try:
            from ..utils.radii import PAULING_EN
        except ImportError:                              # pragma: no cover
            from amorphgen.utils.radii import PAULING_EN

        def headline_key(kv):
            # Cation edges first: they are the ones measured. An O or Cl
            # K edge sits at 0.5-2.8 keV and rarely reaches k = 12, so
            # quoting "O-Ga" -- whose bias differs from Ga-O's, being
            # weighted by Ga's |f(k)| rather than O's -- would point the
            # reader at a fit nobody does. Then the largest bias.
            d = kv[1]
            en_abs = PAULING_EN.get(d["absorber"], 0.0)
            en_scat = PAULING_EN.get(d["scatterer"], 0.0)
            return (en_abs < en_scat, round(abs(d["N_bias_percent"]), 6))

        worst = max(pool, key=headline_key)
        lines.append("  Compare a published EXAFS N against the 'harmonic "
                     "fit' column, not the")
        lines.append("  geometric one: they are different quantities. For "
                     f"{worst[0]} a fit of this")
        lines.append(f"  ensemble would report N = {worst[1]['N_fit']:.2f} "
                     f"where the structure has {worst[1]['N_geom']:.2f}")
        bias_err = worst[1].get("N_bias_percent_err")
        tail = (f"({worst[1]['N_bias_percent']:+.1f}%)" if bias_err is None
                else f"({worst[1]['N_bias_percent']:+.1f} +/- "
                     f"{bias_err:.1f}%)")
        lines.append(f"  {tail}, so that much of any experiment-simulation "
                     "gap")
        lines.append("  is the Gaussian assumption rather than the "
                     "structure.")
        if quality(worst[1]) == "poor":
            lines.append(f"  That fit is POOR ({', '.join(codes(worst[1]))}): "
                         "read the bias as its direction and")
            lines.append("  rough size, not as a number to hold against a "
                         "published N.")
    else:
        lines.append("  No pair has a usable harmonic fit, so there is no "
                     "fitted N to compare")
        lines.append("  a published one against.")
    lines.append("")

    if "n_boot" in first:
        lines.append(f"  Every +/- is an ensemble-sampling standard error "
                     f"from {first['n_boot']} bootstrap")
        lines.append("  resamples of the structures. A difference between "
                     "two ensembles that is")
        lines.append("  smaller than these is not a result.")
        if first["n_structures"] < MIN_BOOTSTRAP_STRUCTURES:
            lines.append(f"  With only {first['n_structures']} structures "
                         f"the bars are themselves unreliable and likely")
            lines.append(f"  too narrow; {MIN_BOOTSTRAP_STRUCTURES}+ makes "
                         f"them meaningful.")
        lines.append("")
    lines.append("  The bias grows with kmax; use the k-range of the paper "
                 "you are comparing")
    lines.append("  against. A near-zero R-factor means the shell really is "
                 "harmonic and the")
    lines.append("  two columns should agree.")
    lines.append(bar)
    return "\n".join(lines)


def _select_rows(result, bonded_only):
    """Bonded pairs only, by the same rule as the descriptor report."""
    items = sorted(result.items())
    if not bonded_only:
        return items
    from .exafs import is_bonded_pair
    kept = [(key, d) for key, d in items
            if is_bonded_pair(d["absorber"], d["scatterer"])]
    return kept or items


def write_harmonic_csv(result, filepath):
    """Write the geometric/fitted comparison to CSV, one row per pair."""
    cols = ["pair", "absorber", "scatterer", "N_geom", "N_fit",
            "N_bias", "N_bias_percent", "R_geom", "R_fit", "R_bias",
            "sigma2_geom", "sigma2_fit", "sigma2_bias_percent", "C3", "skew",
            "kurt", "e0_shift", "r_factor", "converged", "fit_quality",
            "quality_flags", "amplitude_weighted", "kmin", "kmax",
            "kweight", "mfp", "n_structures"]
    err_cols = [c for c in ("N_geom_err", "N_fit_err", "N_bias_percent_err",
                            "R_geom_err", "R_fit_err", "sigma2_geom_err",
                            "sigma2_fit_err", "skew_err", "n_boot")
                if result and c in next(iter(result.values()))]
    cols += err_cols
    with open(filepath, "w") as fh:
        fh.write(",".join(cols) + "\n")
        for key, d in sorted(result.items()):
            values = [key]
            for col in cols[1:]:
                v = d[col]
                if isinstance(v, str):
                    values.append(v)
                elif isinstance(v, bool):
                    values.append("true" if v else "false")
                else:
                    values.append(f"{v:.6g}")
            fh.write(",".join(values) + "\n")
    return filepath
